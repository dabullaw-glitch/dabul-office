def price_line(sid, digits=False):
    s = P.SV[sid]; fp = P.from_price(s); frm = B.is_from(sid)
    w = '{:,}'.format(fp) if digits else W[fp]
    t = ('המחיר מתחיל מ־%s ₪, ועוד מע״מ.' if digits else 'המחיר מתחיל מ%s שקלים, ועוד מע״מ.') % w if frm else (('מחיר קבוע של %s ₪, ועוד מע״מ.' if digits else 'מחיר קבוע של %s שקלים, ועוד מע״מ.') % w)
    if s.get('gov'): t += ' האגרות למדינה משולמות בנפרד.'
    return t + ' המחיר הסופי מוצג לפני התשלום.'

TPL = open('/tmp/claude-0/svcvid/tpl.html', encoding='utf8').read()
CHECK = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="M5 12.5l4.5 4.5L19 7.5"/></svg>'

def scene(sid):
    s, c, d = P.SV[sid], P.C[sid], S[sid]; dm = B.D[d['dom']]
    fp = P.from_price(s); vat = round(fp * P.VAT, 2)
    narr = list(d['n']); narr[4] = price_line(sid)
    caps = list(d['n']); caps[4] = price_line(sid, True)
    who = ''.join('<div class="who" id="w%d"><i>%s</i><span>%s</span></div>' % (k + 1, CHECK, E(x)) for k, x in enumerate(c['who'][:3]))
    incl = s['incl'][:4]
    inc = ''.join('<div class="inc" id="n%d"><b>%d</b><span>%s</span></div>' % (k + 1, k + 1, E(x)) for k, x in enumerate(incl))
    steps = ''.join('<div class="st" id="l%d"><span class="n" id="sn%d">%d</span><div><b>%s</b><span>%s</span></div></div>' % (k + 1, k + 1, k + 1, E(a), E(b)) for k, (a, b) in enumerate(P.STEPS[s['sign']]))
    form = ''.join('<div class="fld">%s</div><div class="inp" id="i%d" data-v="%s"></div>' % (E(q), k + 1, E(v)) for k, (q, v) in enumerate(d['form']))
    rep = {
        '{{TITLE1}}': E(d['t1'][0]), '{{TITLE2}}': E(d['t1'][1]), '{{TITLE3}}': E(d.get('t3', 'אונליין.')), '{{SVC}}': E(s['title']), '{{DOM}}': E(dm[1]), '{{DC}}': dm[2], '{{DT}}': dm[3],
        '{{DICON}}': B.ic(dm[4], '2'), '{{FORM}}': form, '{{UP}}': E(d['up']), '{{WHO}}': who, '{{INC}}': inc, '{{NINC}}': str(len(incl)), '{{STEPS}}': steps,
        '{{PRICE}}': '{:,}'.format(fp), '{{VAT}}': '{:,.2f}'.format(vat), '{{TOTAL}}': '{:,.2f}'.format(fp + vat), '{{FROM}}': 'החל מ־' if B.is_from(sid) else 'מחיר קבוע',
        '{{GOV}}': ('אגרות למדינה בנפרד' if s.get('gov') else 'בלי תוספות בהמשך'), '{{SLA}}': E(HB.TIME[sid]), '{{SLUG}}': s['slug'],
        '{{CAPS}}': json.dumps(caps, ensure_ascii=False),
    }
    h = TPL
    for k, v in rep.items(): h = h.replace(k, v)
    assert '{{' not in h, sid
    for bad in ('—', '–', 'מומחה', 'חינם', 'הטוב ביותר'):
        assert bad not in h and all(bad not in x for x in narr), (sid, bad)
    os.makedirs('/tmp/claude-0/svcvid/scenes', exist_ok=True)
    open('/tmp/claude-0/svcvid/scenes/%s.html' % sid, 'w', encoding='utf8').write(h)
    return narr

