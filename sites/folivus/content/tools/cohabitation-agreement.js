// מחולל טיוטת הסכם חיים משותפים (ידועים בציבור) - פוליבוס. מודול טהור.

export const CONFIG = {
  defaultNoticeDays: 90,
};

const esc = (v) => String(v ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const val = (v) => (v === undefined || v === null || String(v).trim() === "" ? "__________" : esc(String(v).trim()));
const date = (s) => (typeof s === "string" && /^\d{4}-\d{2}-\d{2}$/.test(s) ? s.split("-").reverse().join(".") : "__________");
const lines = (t) => String(t ?? "").split(/\n+/).map((x) => x.trim()).filter(Boolean);
const OWN = {
  a: (A) => `הדירה בבעלות ${A} בלבד, והיא תישאר בבעלותו הבלעדית גם אם הצד השני ישתתף בהוצאות השוטפות או בשיפוצים, אלא אם הוסכם אחרת בכתב.`,
  b: (A, B) => `הדירה בבעלות ${B} בלבד, והיא תישאר בבעלותו הבלעדית גם אם הצד השני ישתתף בהוצאות השוטפות או בשיפוצים, אלא אם הוסכם אחרת בכתב.`,
  joint: () => "הדירה רשומה על שם שני הצדדים בחלקים שווים, אלא אם נרשם אחרת בלשכת רישום המקרקעין, וכל צד זכאי לחלקו הרשום.",
  rented: () => "הדירה שכורה. שני הצדדים יחתמו על הסכם השכירות, ויישאו בדמי השכירות לפי חלוקת ההוצאות שבהסכם זה.",
};

export function generate(inputs = {}) {
  const warnings = [];
  const A = val(inputs.party_a_name);
  const B = val(inputs.party_b_name);
  if (!inputs.party_a_name || !inputs.party_b_name) warnings.push("חסרים שמות הצדדים.");
  if (!inputs.party_a_id || !inputs.party_b_id) warnings.push("חסרים מספרי תעודת זהות.");
  const own = OWN[inputs.home_ownership] ? inputs.home_ownership : "rented";
  const split = inputs.expense_split || "equal";
  const pctA = Number(inputs.party_a_percent);
  if (split === "custom" && !(pctA > 0 && pctA < 100)) warnings.push("בחלוקה לפי אחוזים יש להזין את חלקו של הצד הראשון (בין 1 ל-99).");
  const splitText = split === "income"
    ? "ההוצאות השוטפות של משק הבית יחולקו בין הצדדים באופן יחסי להכנסה החודשית נטו של כל אחד מהם."
    : split === "custom" && pctA > 0 && pctA < 100
      ? `ההוצאות השוטפות של משק הבית יחולקו כך: ${A} ${pctA}% ו-${B} ${100 - pctA}%.`
      : "ההוצאות השוטפות של משק הבית יחולקו בין הצדדים בחלקים שווים.";
  const notice = Number(inputs.notice_days) > 0 ? Math.round(Number(inputs.notice_days)) : CONFIG.defaultNoticeDays;
  const sepA = lines(inputs.party_a_separate_assets);
  const sepB = lines(inputs.party_b_separate_assets);
  const list = (arr) => (arr.length ? `<ul>${arr.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>` : "<p>__________</p>");
  let n = 0;
  const p = (t) => `<p>${++n}. ${t}</p>`;

  const html = `<div dir="rtl" lang="he">
<h1>הסכם חיים משותפים</h1>
<p>שנערך ונחתם ב-${val(inputs.sign_place)} ביום ${date(inputs.sign_date)}</p>
<p><strong>בין:</strong> ${A}, ת"ז ${val(inputs.party_a_id)}, מ-${val(inputs.party_a_address)} (להלן: "הצד הראשון")</p>
<p><strong>לבין:</strong> ${B}, ת"ז ${val(inputs.party_b_id)}, מ-${val(inputs.party_b_address)} (להלן: "הצד השני")</p>
<p>הואיל והצדדים מנהלים חיים משותפים ומשק בית משותף החל מיום ${date(inputs.cohabitation_start)}, ומבקשים להסדיר את היחסים הרכושיים ביניהם בכתב, בהסכמה ומרצונם החופשי;</p>
<p>לפיכך הוסכם בין הצדדים כדלקמן:</p>
<h2>מבוא ומטרה</h2>
${p("המבוא להסכם זה הוא חלק בלתי נפרד ממנו.")}
${p("מטרת ההסכם היא לקבוע מה שייך לכל צד, איך מתחלקות ההוצאות, ומה יקרה לרכוש אם הקשר יסתיים. אין בהסכם כדי לקבוע את מעמדם האישי של הצדדים.")}
<h2>רכוש נפרד</h2>
${p(`הנכסים, הזכויות והחסכונות הבאים שייכים ל${A} בלבד, וכך גם פירותיהם, תמורתם וכל נכס שיבוא במקומם:`)}
${list(sepA)}
${p(`הנכסים, הזכויות והחסכונות הבאים שייכים ל${B} בלבד, וכך גם פירותיהם, תמורתם וכל נכס שיבוא במקומם:`)}
${list(sepB)}
${p("ירושות ומתנות שיקבל צד במהלך החיים המשותפים, וכן זכויות פנסיוניות, קופות גמל וקרנות השתלמות הרשומות על שמו, יישארו שלו בלבד, אלא אם הוסכם אחרת בכתב.")}
<h2>דירת המגורים</h2>
${p(`הצדדים מתגוררים בדירה ב${val(inputs.home_address)}.`)}
${p(OWN[own](A, B))}
<h2>הוצאות משק הבית</h2>
${p(splitText)}
${inputs.joint_account === true || inputs.joint_account === "true"
    ? p("הצדדים רשאים לנהל חשבון בנק משותף לצורך ההוצאות השוטפות. יתרת החשבון המשותף תחולק ביניהם בחלקים שווים בסיום הקשר, אלא אם יוכח שהכסף הופקד לחשבון לטובת צד אחד בלבד.")
    : p("כל צד ינהל את חשבון הבנק שלו בנפרד, ואין בהעברת כספים לצורך הוצאות משותפות כדי ליצור שיתוף בחשבון.")}
${p("רכוש שנרכש במשותף ובכסף משותף בתקופת החיים המשותפים, יתחלק בחלקים שווים, אלא אם נרשם אחרת או הוסכם אחרת בכתב. חובות שצד נטל על עצמו ללא הסכמת הצד השני בכתב, יחולו עליו בלבד.")}
<h2>סיום הקשר</h2>
${p(`כל צד רשאי לסיים את החיים המשותפים בהודעה בכתב לצד השני.`)}
${p(`צד שאינו בעל הדירה יפנה אותה בתוך ${notice} ימים מיום מסירת ההודעה, ולא יהיו לו כל זכויות בדירה, למעט החזר כספים שהשקיע בה אם הוסכם על כך בכתב.`)}
${p("הרכוש המשותף יחולק לפי הסכם זה. אם הצדדים לא יגיעו להסכמה על אופן החלוקה, הם יפנו תחילה לגישור, ורק אם הגישור לא יצליח, לבית המשפט המוסמך.")}
${p("הצדדים מצהירים כי אין בהסכם זה כדי לגרוע מזכויותיהם ומחובותיהם כלפי ילדים משותפים, ובכלל זה מזונות והסדרי שהות, שייקבעו לטובת הילדים בלבד.")}
<h2>שונות</h2>
${p("שינוי של הסכם זה ייעשה רק בכתב ובחתימת שני הצדדים.")}
${p("הצדדים מצהירים כי קראו את ההסכם, הבינו אותו, ניתנה להם הזדמנות להתייעץ עם עורך דין, וחתמו עליו מרצונם החופשי.")}
${p("הצדדים רשאים לפנות לבית המשפט לענייני משפחה או לנוטריון כדי לאשר הסכם זה, וזאת כדי לחזק את מעמדו הראייתי.")}
<p>ולראיה באו הצדדים על החתום:</p>
<p>__________________ &nbsp;&nbsp;&nbsp;&nbsp; __________________<br>${A} &nbsp;&nbsp;&nbsp;&nbsp; ${B}</p>
<p><em>טיוטה כללית שהופקה בכלי של פוליבוס. היא אינה ייעוץ משפטי ואינה מחליפה התאמה ובדיקה של עורך דין לפני חתימה.</em></p>
</div>`;
  warnings.push("מומלץ שכל צד יתייעץ עם עורך דין משלו לפני החתימה, ולשקול אישור ההסכם בבית המשפט לענייני משפחה או בפני נוטריון.");
  if (inputs.married === true || inputs.married === "true") warnings.push("בני זוג נשואים צריכים הסכם ממון לפי חוק יחסי ממון בין בני זוג, שטעון אישור של בית משפט או בית דין דתי (ולפני הנישואין גם אימות בדרכים נוספות שבחוק). הטיוטה הזו מיועדת לידועים בציבור.");
  return { title: "הסכם חיים משותפים", html, warnings };
}
