// מחולל טיוטת תוכנית הורות (הסדרי שהות ואחריות הורית) - פוליבוס. מודול טהור.
// הסכם בין הורים החיים בנפרד טעון אישור בית המשפט (סעיף 24 לחוק הכשרות המשפטית והאפוטרופסות).

export const CONFIG = {
  defaultTravelNoticeDays: 30,
  defaultRelocationNoticeDays: 90,
};

const esc = (v) => String(v ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const val = (v) => (v === undefined || v === null || String(v).trim() === "" ? "__________" : esc(String(v).trim()));
const date = (s) => (typeof s === "string" && /^\d{4}-\d{2}-\d{2}$/.test(s) ? s.split("-").reverse().join(".") : "__________");
const lines = (t) => String(t ?? "").split(/\n+/).map((x) => x.trim()).filter(Boolean);

const SCHEDULES = {
  equal_223: "הילדים ישהו אצל כל הורה בחלוקה שווה לפי מחזור של שבועיים: שני ימים אצל הורה אחד, שני ימים אצל ההורה השני, ושלושה ימים (כולל סוף שבוע) לסירוגין.",
  equal_week: "הילדים ישהו שבוע אצל כל הורה לסירוגין. ההחלפה תתבצע ביום ראשון בסיום יום הלימודים.",
  primary_a: (A, B) => `מקום המגורים העיקרי של הילדים יהיה אצל ${A}. הילדים ישהו אצל ${B} בשני ימים קבועים באמצע השבוע אחרי הלימודים ועד שעת השינה, ובכל סוף שבוע שני מיום שישי אחרי הלימודים ועד יום ראשון בבוקר.`,
  primary_b: (A, B) => `מקום המגורים העיקרי של הילדים יהיה אצל ${B}. הילדים ישהו אצל ${A} בשני ימים קבועים באמצע השבוע אחרי הלימודים ועד שעת השינה, ובכל סוף שבוע שני מיום שישי אחרי הלימודים ועד יום ראשון בבוקר.`,
  custom: () => "",
};

export function generate(inputs = {}) {
  const warnings = [];
  const A = val(inputs.parent_a_name);
  const B = val(inputs.parent_b_name);
  const kids = lines(inputs.children);
  if (!inputs.parent_a_name || !inputs.parent_b_name) warnings.push("חסרים שמות ההורים.");
  if (!kids.length) warnings.push("חסרים פרטי הילדים (שם ותאריך לידה).");
  const sched = SCHEDULES[inputs.schedule_type] !== undefined ? inputs.schedule_type : "equal_223";
  let schedText = typeof SCHEDULES[sched] === "function" ? SCHEDULES[sched](A, B) : SCHEDULES[sched];
  if (sched === "custom") {
    schedText = inputs.custom_schedule ? esc(inputs.custom_schedule) : "__________";
    if (!inputs.custom_schedule) warnings.push("נבחר הסדר מותאם אישית אבל לא נכתב פירוט.");
  }
  const travel = Number(inputs.travel_notice_days) > 0 ? Math.round(Number(inputs.travel_notice_days)) : CONFIG.defaultTravelNoticeDays;
  const reloc = Number(inputs.relocation_notice_days) > 0 ? Math.round(Number(inputs.relocation_notice_days)) : CONFIG.defaultRelocationNoticeDays;
  const summerWeeks = Number(inputs.summer_weeks_each) > 0 ? Math.round(Number(inputs.summer_weeks_each)) : null;
  let n = 0;
  const p = (t) => `<p>${++n}. ${t}</p>`;

  const html = `<div dir="rtl" lang="he">
<h1>תוכנית הורות: אחריות הורית והסדרי שהות</h1>
<p>בין ${A}, ת"ז ${val(inputs.parent_a_id)} לבין ${B}, ת"ז ${val(inputs.parent_b_id)} (להלן: "ההורים")</p>
<p>הילדים: ${kids.length ? kids.map(esc).join("; ") : "__________"}</p>
<h2>עקרונות</h2>
${p("ההורים הם האפוטרופסים הטבעיים של ילדיהם, וימשיכו לשאת יחד באחריות לגידולם, לחינוכם ולבריאותם, גם כשהם חיים בנפרד. טובת הילדים היא השיקול המרכזי בכל החלטה.")}
${p("ההורים יכבדו זה את זה בנוכחות הילדים, לא ישתפו את הילדים במחלוקות ביניהם ולא ישתמשו בהם כשליחים.")}
<h2>הסדר שהות שבועי</h2>
${p(schedText)}
${p(`ההעברות יתבצעו ${inputs.handover_place ? `ב${esc(inputs.handover_place)}` : "במוסד החינוכי או בבית ההורה שאצלו נמצאים הילדים"}, בזמנים שנקבעו. שינוי חד פעמי ייעשה בתיאום מראש ובהסכמה.`)}
<h2>חגים וחופשות</h2>
${p("חגי ישראל יחולקו לסירוגין: בשנה אחת יהיו הילדים בחג מסוים אצל הורה אחד, ובשנה שאחריה אצל ההורה השני. חג שנמשך כמה ימים יחולק באופן שווה ככל האפשר.")}
${p(summerWeeks ? `בחופשת הקיץ כל הורה יהיה זכאי ל-${summerWeeks} שבועות רצופים עם הילדים, בתיאום מראש עד 1 במאי בכל שנה.` : "בחופשת הקיץ ובחופשות הארוכות ימי החופשה יחולקו באופן שווה, בתיאום מראש.")}
${p("ימי הולדת של הילדים ושל ההורים, יום האם ויום המשפחה יתואמו כך שהילדים יוכלו לחגוג עם כל הורה.")}
<h2>החלטות מהותיות</h2>
${p("החלטות מהותיות על חינוך, טיפול רפואי שאינו דחוף, טיפול רגשי, חוגים יקרים ומקום המגורים יתקבלו בהסכמת שני ההורים. בעניין דחוף רשאי כל הורה לפעול לבד ולעדכן את ההורה השני בהקדם.")}
${p("שני ההורים זכאים לקבל מידע מלא ממוסדות החינוך ומגורמי הבריאות, ולהשתתף באסיפות הורים ובאירועים.")}
<h2>תקשורת</h2>
${p("הילדים יוכלו לשוחח עם ההורה שאינו שוהה איתם בכל יום בשעה סבירה, בטלפון או בשיחת וידאו.")}
${p("ההורים יעדכנו זה את זה בכתב (למשל בהודעה) בכל עניין חשוב שנוגע לילדים.")}
<h2>נסיעות ומעבר דירה</h2>
${p(`נסיעה של הילדים לחו"ל עם אחד ההורים תתואם בכתב לפחות ${travel} ימים מראש, כולל יעד, תאריכים ופרטי קשר. ההורה השני לא יסרב בלי סיבה סבירה. ראו גם מכתב הסכמה ליציאת קטין לחו"ל.`)}
${p(`הורה שמתכנן מעבר דירה שישפיע על הסדרי השהות או על מסגרת החינוך יודיע על כך בכתב לפחות ${reloc} ימים מראש, וההורים ינסו להגיע להסכמה על התאמת ההסדרים.`)}
<h2>יישוב מחלוקות ושינויים</h2>
${p("במחלוקת יפנו ההורים תחילה לשיחה ישירה, אחר כך לגישור או לתיאום הורי, ורק אם אלה לא הצליחו, לבית המשפט לענייני משפחה.")}
${p("ההורים יבחנו את התוכנית מחדש כשהילדים גדלים או כשמשתנות הנסיבות. שינוי ייעשה בכתב ובאישור בית המשפט.")}
${p("ההורים יגישו תוכנית זו לאישור בית המשפט לענייני משפחה, והיא תיכנס לתוקף עם אישורה.")}
<p>__________________ &nbsp;&nbsp;&nbsp;&nbsp; __________________<br>${A} &nbsp;&nbsp;&nbsp;&nbsp; ${B}</p>
<p>תאריך: ${date(inputs.sign_date)}</p>
<p><em>טיוטה כללית שהופקה בכלי של פוליבוס. היא אינה ייעוץ משפטי ואינה מחליפה התייעצות עם עורך דין או גורם טיפולי.</em></p>
</div>`;
  warnings.push("הסכם בין הורים החיים בנפרד על אפוטרופסות ושהות טעון אישור של בית המשפט, שיאשר אותו רק אם הוא לטובת הילדים.");
  warnings.push("מזונות ומדור אינם כלולים בטיוטה זו ונקבעים בנפרד. ראו אומדן מזונות ילדים.");
  return { title: "תוכנית הורות והסדרי שהות", html, warnings };
}
