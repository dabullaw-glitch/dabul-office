function dabul_tfix_enc($path) {
	return implode('/', array_map(function ($s) { return $s === '' ? '' : rawurlencode($s); }, explode('/', $path)));
}
function dabul_tfix_links($html) {
	if (!is_string($html) || $html === '' || stripos($html, 'href') === false) return $html;
	$map = dabul_tfix_map();
	return preg_replace_callback('#href=(["\'])((?:https?:)?//(?:www\.)?dabullaw\.co\.il)?(/[^"\'\#?\s]*)([^"\']*)\1#i', function ($m) use ($map) {
		$p = rawurldecode($m[3]);
		if (!isset($map[$p])) return $m[0];
		return 'href=' . $m[1] . 'https://dabullaw.co.il' . dabul_tfix_enc($map[$p]) . $m[4] . $m[1];
	}, $html);
}
